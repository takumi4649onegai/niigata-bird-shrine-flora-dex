// 計算用：新潟市（北緯37.9度, 東経139.0度）のリアルタイム日没・マジックアワー算出
window.calculateNiigataSunset = function(date = new Date()) {
  const lat = 37.916; // 新潟市北区・中央区付近
  const lng = 139.036;
  const rad = Math.PI / 180;
  
  // 1年の日数と近似赤緯・均時差
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = (date - start) + ((start.getTimezoneOffset() - date.getTimezoneOffset()) * 60 * 1000);
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // 太陽赤緯 delta
  const delta = 23.45 * Math.sin(rad * (360 / 365) * (dayOfYear - 81));
  // 日没時角 omega0 (度)
  const cosOmega = -Math.tan(lat * rad) * Math.tan(delta * rad);
  const omega0 = Math.acos(Math.max(-1, Math.min(1, cosOmega))) / rad;
  
  // 太陽南中時 (日本標準時・東経135度との差)
  const solarNoon = 12 - (lng - 135) / 15;
  const sunsetHours = solarNoon + (omega0 / 15);
  
  const hour = Math.floor(sunsetHours);
  const minute = Math.floor((sunsetHours - hour) * 60);
  
  const sunsetDate = new Date(date);
  sunsetDate.setHours(hour, minute, 0, 0);
  
  // マジックアワー（日没15分前〜日没15分後）
  const magicStart = new Date(sunsetDate.getTime() - 15 * 60 * 1000);
  const magicEnd = new Date(sunsetDate.getTime() + 15 * 60 * 1000);
  
  const pad = n => String(n).padStart(2, '0');
  return {
    sunsetTimeStr: `${pad(hour)}:${pad(minute)}`,
    magicStartStr: `${pad(magicStart.getHours())}:${pad(magicStart.getMinutes())}`,
    magicEndStr: `${pad(magicEnd.getHours())}:${pad(magicEnd.getMinutes())}`,
    sunsetDate: sunsetDate
  };
};
